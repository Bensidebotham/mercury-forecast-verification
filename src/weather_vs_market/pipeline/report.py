"""Write the README results block and docs/RESULTS.md from results/backtest_test.json.

Numbers in the docs are generated, never typed: rerun `wvm backtest report`
after scoring and the README follows the data.
"""
import json
import re
from pathlib import Path

VENUES = {"kalshi": "Kalshi", "polymarket": "Polymarket"}


def _s(x: float, d: int = 3) -> str:
    return f"{x:+.{d}f}"


def _ci(r: dict, metric: str) -> str:
    lo, hi = r[f"{metric}_diff_ci"]
    return f"{_s(r[f'{metric}_diff'])} [{_s(lo)}, {_s(hi)}]"


def _scored(doc: dict):
    for venue, v in doc["venues"].items():
        for r in v["summary"]:
            yield venue, v, r


_METRICS = ("brier", "rps", "logscore")


def _direction(rows: list[dict], metric: str) -> str:
    """'market' / 'model' if every lead's interval excludes zero the same way, else 'mixed'/'none'."""
    market = all(r[f"{metric}_diff_ci"][0] > 0 for r in rows)
    model = all(r[f"{metric}_diff_ci"][1] < 0 for r in rows)
    clear = any(r[f"{metric}_diff_ci"][0] > 0 or r[f"{metric}_diff_ci"][1] < 0 for r in rows)
    return "market" if market else "model" if model else "mixed" if clear else "none"


def _month(iso: str) -> str:
    from datetime import date
    return date.fromisoformat(iso).strftime("%b %Y")


_VERDICT = {"market": "the market was more accurate than the model at every lead time",
            "model": "the model was more accurate than the market at every lead time",
            "mixed": "the result differed by lead time",
            "none": "there was no clear difference between model and market"}


def headline(doc: dict) -> str:
    venues = []
    for venue, v in doc["venues"].items():
        rows = v["summary"]
        if not rows:
            continue
        ns = sorted(r["n_events"] for r in rows)
        n = f"{ns[0]:,}" if ns[0] == ns[-1] else f"{ns[0]:,}–{ns[-1]:,}"
        brier = _direction(rows, "brier")
        all_scores = brier in ("market", "model") and all(_direction(rows, m) == brier for m in _METRICS)
        venues.append((VENUES.get(venue, venue), n, brier, all_scores, v["date_span"]))
    if not venues:
        return "No test-window events have been scored yet."
    spans = [s for *_, s in venues if s]
    when = f" ({_month(min(s[0] for s in spans))} – {_month(max(s[1] for s in spans))})" if spans else ""
    tail = (" Every comparison uses a 95% paired bootstrap interval over city-days; see the table below "
            "and [docs/RESULTS.md](docs/RESULTS.md).")
    if len({(b, a) for _, _, b, a, _ in venues}) == 1:
        _, _, brier, all_scores, _ = venues[0]
        counts = " and ".join(f"{name} ({n} city-days per lead time)" for name, n, *_ in venues)
        scores = "on Brier, RPS and log score alike" if all_scores else "on Brier score"
        return f"**Out of sample{when}, {_VERDICT[brier]}, on {counts}, {scores}.**" + tail
    parts = [f"{name} ({n} city-days per lead time): {_VERDICT[b]}" + ("" if a else " on Brier score")
             for name, n, b, a, _ in venues]
    return f"**Out of sample{when}:** " + "; ".join(parts) + "." + tail


def results_table(doc: dict) -> str:
    rows = ["| Venue | Lead | City-days | Model Brier | Market Brier | Model − market [95% CI] |",
            "|---|---|---:|---:|---:|---|"]
    for venue, _, r in _scored(doc):
        rows.append(f"| {VENUES.get(venue, venue)} | {r['lead']} | {r['n_events']:,} | "
                    f"{r['model_brier']:.3f} | {r['market_brier']:.3f} | {_ci(r, 'brier')} |")
    return "\n".join(rows)


def full_report(doc: dict) -> str:
    lines = [
        "# Backtest results", "",
        "Generated by `uv run wvm backtest report` from `results/backtest_test.json`; "
        "do not edit by hand.", "",
        f"- Test window: {doc['window'][0]} to {doc['window'][1]}; parameters fit on "
        f"{doc['train_window'][0]} to {doc['train_window'][1]} only.",
        f"- Code version: `{(doc.get('git_sha') or 'unknown')[:7]}`. "
        "Protocol: [PROTOCOL.md](PROTOCOL.md).", "",
        "## Summary", "", headline(doc).split(" Every comparison")[0], "",
        "## All scores", "",
        "Per city-day means; lower is better for all three. Differences are model − market.", "",
        "| Venue | Lead | City-days | Brier (model / market) | Brier diff | RPS diff | Log-score diff |",
        "|---|---|---:|---|---|---|---|",
    ]
    for venue, _, r in _scored(doc):
        lines.append(f"| {VENUES.get(venue, venue)} | {r['lead']} | {r['n_events']:,} | "
                     f"{r['model_brier']:.3f} / {r['market_brier']:.3f} | {_ci(r, 'brier')} | "
                     f"{_ci(r, 'rps')} | {_ci(r, 'logscore')} |")
    lines += ["", "## Events scored and dropped", "",
              "`events_in_window` counts city-days; the other counts are (city-day, lead point) pairs.", ""]
    for venue, v in doc["venues"].items():
        stats = ", ".join(f"{k} {n:,}" for k, n in sorted(v["stats"].items())) or "none"
        lines.append(f"- {VENUES.get(venue, venue)}: {stats}")
    agree = doc["data_quality"]["kalshi_cli_agreement"]
    if agree.get("n"):
        lines += ["", "## Data quality", "",
                  f"- The NWS CLI daily high fell in Kalshi's winning bucket on {agree['agree']:,} of "
                  f"{agree['n']:,} test city-days ({agree['rate']:.1%}). Kalshi switched its settlement "
                  "source to The Weather Company around 2026-08-14; scores use Kalshi's own result."]
    cities = [(venue, c) for venue, v in doc["venues"].items() for c in v["by_city"]]
    if cities:
        lines += ["", "## By city (context only)", "",
                  "| Venue | City | Lead | City-days | Model Brier | Market Brier |",
                  "|---|---|---|---:|---:|---:|"]
        lines += [f"| {VENUES.get(venue, venue)} | {c['city']} | {c['lead']} | {c['n_events']:,} | "
                  f"{c['model_brier']:.3f} | {c['market_brier']:.3f} |" for venue, c in cities]
    return "\n".join(lines) + "\n"


def replace_block(path: Path, name: str, content: str) -> None:
    text = path.read_text()
    pattern = re.compile(rf"(<!-- {name}:start -->\n).*?(<!-- {name}:end -->)", re.S)
    if not pattern.search(text):
        raise ValueError(f"no {name} markers in {path}")
    path.write_text(pattern.sub(lambda m: f"{m.group(1)}{content}\n{m.group(2)}", text))


def write_reports(results: Path, readme: Path, out: Path) -> None:
    doc = json.loads(results.read_text())
    replace_block(readme, "headline", headline(doc))
    replace_block(readme, "results", results_table(doc))
    out.write_text(full_report(doc))
